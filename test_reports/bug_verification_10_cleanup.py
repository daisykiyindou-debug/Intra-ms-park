#!/usr/bin/env python3
"""Cleanup QA records created by bug verification iteration 10."""
import asyncio

from dotenv import dotenv_values
from motor.motor_asyncio import AsyncIOMotorClient


async def main():
    env = dotenv_values("/app/backend/.env")
    mongo_url = env.get("MONGO_URL", "mongodb://localhost:27017").strip('"')
    db_name = env.get("DB_NAME", "test_database").strip('"')
    client = AsyncIOMotorClient(mongo_url)
    db = client[db_name]
    notif_res = await db.notifications.delete_many({
        "$or": [
            {"id": {"$in": ["qa-notif-click-10", "qa-notif-markall-10", "qa-notif-read-10"]}},
            {"title": {"$in": ["QA_NOTIFICATION_CLICK_10", "QA_NOTIFICATION_MARKALL_10", "QA_NOTIFICATION_READ_10"]}},
        ]
    })
    post_res = await db.posts.delete_many({"title": "QA avatar officiel MS Park 10"})
    # Remove notification generated by the QA post broadcast to Idriss if present.
    broadcast_res = await db.notifications.delete_many({
        "employee_id": "emp-idriss-malonga",
        "type": "post",
        "title": "Nouvelle publication",
        "content": {"$regex": "QA avatar officiel MS Park 10"},
    })
    client.close()
    print({
        "notifications_deleted": notif_res.deleted_count,
        "posts_deleted": post_res.deleted_count,
        "broadcast_notifications_deleted": broadcast_res.deleted_count,
    })


if __name__ == "__main__":
    asyncio.run(main())